function raidMethod({
  id,
  name,
  shortName,
  category,
  recipe,
  expandedCost,
  yieldAmount = 1,
  time,
  tags = [],
  sourceName = 'Facepunch Rust Wiki',
  sourceUrl,
}) {
  return {
    id,
    name,
    category,
    icon: shortName ? facepunchIcon(shortName) : null,
    shortName,
    recipe,
    expandedCost,
    yield: yieldAmount,
    time,
    tags,
    sourceName,
    sourceUrl: sourceUrl || (shortName ? facepunchItemUrl(shortName) : null),
  };
}

